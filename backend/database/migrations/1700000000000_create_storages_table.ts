import { BaseSchema } from '@adonisjs/lucid/schema'

/**
 * The neutral file record that `#models/storage` and the kit storage repository read. The
 * binary never passes through the application: `POST /storages` writes the row, the browser
 * uploads the parts straight to the bucket, and the confirmation turns `PENDING` into
 * `UPLOADED`. It runs before `users`, whose `avatar_id` references it.
 */
export default class extends BaseSchema {
  protected tableName = 'storages'

  override up(): Promise<void> {
    this.schema.createTable(this.tableName, (table) => {
      table
        .uuid('id')
        .primary()
        .defaultTo(this.db.knexRawQuery('gen_random_uuid()'))
      // `filename` is generated by the system (uuid plus extension); `original_name` keeps
      // only the label the user sent and never becomes a bucket path.
      table.string('filename', 255).notNullable()
      table.string('original_name', 255).notNullable()
      table.string('mimetype', 127).notNullable()
      // `bigint`: the `int4` ceiling is 2.1 GB, below what `UPLOAD_MAX_SIZE` may ask for, and
      // the column type would become the real limit hidden behind the validation.
      table.bigint('size').notNullable()
      // The object key in the bucket. No `url` column: it is derived on read, so changing
      // bucket or CDN needs no data migration.
      table.string('path', 255).notNullable()
      // Literal values (DECISIONS.md #354): they match `UPLOAD_STATUS` in the shared.
      table
        .enum('status', ['PENDING', 'UPLOADED'])
        .notNullable()
        .defaultTo('PENDING')
      // The multipart `UploadId`; null when the file went up in a single PUT.
      table.string('upload_id', 255).nullable()
      // Resuming re-slices the file, and the boundaries must match the parts already sent.
      table.integer('part_size').nullable()
      table.timestamp('created_at').notNullable()
      table.timestamp('updated_at').nullable()
      // Soft delete: removing the row does not remove the binary in the bucket.
      table.timestamp('deleted_at').nullable()
      // Serves the sweep of abandoned `PENDING` rows (`node ace storages:prune`).
      table.index(['status', 'created_at'])
    })

    return Promise.resolve()
  }

  override down(): Promise<void> {
    this.schema.dropTable(this.tableName)

    return Promise.resolve()
  }
}
